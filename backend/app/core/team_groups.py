# Алиасы на случай, если Flashscore пишет название команды иначе,
# чем в списке выше. Ключ — вариант с Flashscore, значение — каноничное
# имя из GROUPS. Заполнять по мере обнаружения несовпадений в логах
# ("⚠️ group_letter не определён для команды: ...").
ALIASES: dict[str, str] = {}

# Обратный индекс: имя команды → буква группы. Строится один раз при импорте.
_TEAM_TO_GROUP: dict[str, str] = {
    team: letter for letter, teams in GROUPS.items() for team in teams
}


def get_group_letter(team_name: str) -> str | None:
    """Возвращает букву группы для команды или None, если не найдена."""
    name = ALIASES.get(team_name, team_name)
    return _TEAM_TO_GROUP.get(name)